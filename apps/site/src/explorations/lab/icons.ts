export type IconName = keyof typeof RAW;

/** The icon as rows of exactly 12 characters, 12 rows. */
export function iconRows(name: string): string[] {
  const raw = RAW[name] ?? [];
  return Array.from({ length: 12 }, (_, i) => (raw[i] ?? "").padEnd(12, ".").slice(0, 12));
}

export const ICON_NAMES = Object.keys(RAW);

/** SVG markup: ink pixels follow `currentColor`, signal pixels use `--accent`. */
export function iconSvg(name: string): string {
  let ink = "";
  let sig = "";
  iconRows(name).forEach((row, y) => {
    [...row].forEach((c, x) => {
      if (c === "#") ink += `M${x} ${y}h1v1h-1z`;
      if (c === "o") sig += `M${x} ${y}h1v1h-1z`;
    });
  });
  return `<svg viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true"><path fill="currentColor" d="${ink}"/><path fill="var(--accent)" d="${sig}"/></svg>`;
}
