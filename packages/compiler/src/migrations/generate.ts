import { emptySnapshot, sameSnapshot, snapshotOf, type Snapshot } from "@forgeron/sdk/db";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { loadTool } from "../load";
import { diffSnapshots, MigrationGenerationError } from "./diff";

// `forgeron db generate`: compares `db/schema.ts` with `db/migrations/meta/snapshot.json` (the state
// after the last migration), writes the next migration, then updates the snapshot (docs/sdk.md §8).

const MIGRATIONS_DIR = ["db", "migrations"] as const;
const FILE = /^(\d{4})_([a-z0-9_]+)\.ts$/;

export async function readSnapshot(dir: string): Promise<Snapshot> {
  try {
    return JSON.parse(
      await readFile(join(dir, ...MIGRATIONS_DIR, "meta", "snapshot.json"), "utf8"),
    ) as Snapshot;
  } catch {
    return emptySnapshot();
  }
}

export interface GeneratedMigration {
  /** The file, relative to the tool: `db/migrations/0001_init.ts`. */
  file: string;
  name: string;
  statements: number;
  destructive: boolean;
  /** False when the way back could not be written: the migration has an empty `down`. */
  reversible: boolean;
}

const quote = (sql: string) => `    ${JSON.stringify(sql)},`;

/** Writes the next migration, or returns `undefined` when the schema has not changed. */
export async function generateMigration(
  toolDir: string,
  options: { name?: string } = {},
): Promise<GeneratedMigration | undefined> {
  const dir = resolve(toolDir);
  const scratch = join(dir, ".forgeron", "generate");
  let schema: unknown;
  try {
    schema = (await loadTool(dir, scratch)).schema;
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
  if (schema === undefined)
    throw new Error("This tool has no db/schema.ts: there is nothing to migrate.");

  const previous = await readSnapshot(dir);
  const next = snapshotOf(schema as Parameters<typeof snapshotOf>[0]);
  if (sameSnapshot(previous, next)) return undefined;

  const up = diffSnapshots(previous, next);
  let down: string[] = [];
  let reversible = true;
  try {
    down = diffSnapshots(next, previous).statements;
  } catch (error) {
    if (!(error instanceof MigrationGenerationError)) throw error;
    reversible = false;
  }

  const folder = join(dir, ...MIGRATIONS_DIR);
  await mkdir(join(folder, "meta"), { recursive: true });
  const taken = (await readdir(folder)).map((file) => FILE.exec(file)).filter((m) => m !== null);
  const number = String(Math.max(0, ...taken.map((m) => Number(m[1]))) + 1).padStart(4, "0");
  const name = options.name ?? (taken.length === 0 ? "init" : "update");
  if (!/^[a-z0-9_]+$/.test(name)) {
    throw new Error(`"${name}" is not a migration name: use a-z, 0-9 and "_".`);
  }

  const file = `${number}_${name}.ts`;
  const source = [
    "// Generated by `forgeron db generate`. Read it, and add data statements here if the change needs them.",
    'import { migration } from "@forgeron/sdk/db";',
    "",
    "export default migration({",
    "  up: [",
    ...up.statements.map(quote),
    "  ],",
    reversible
      ? "  down: ["
      : "  // The way back could not be written: this change cannot be undone automatically.\n  down: [",
    ...down.map(quote),
    "  ],",
    ...(up.destructive ? ["  destructive: true,"] : []),
    "});",
    "",
  ].join("\n");
  await writeFile(join(folder, file), source);
  await writeFile(join(folder, "meta", "snapshot.json"), `${JSON.stringify(next, null, 2)}\n`);

  return {
    file: join(...MIGRATIONS_DIR, file),
    name: `${number}_${name}`,
    statements: up.statements.length,
    destructive: up.destructive,
    reversible,
  };
}
