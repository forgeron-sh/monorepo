import { bindChain, type GlChain, type UniformSetter } from "./contract";
import { compileStages } from "./glsl";
import { gridGlsl } from "./passes/grid.glsl";
import { orderedGlsl } from "./passes/ordered.glsl";
import { paletteGlsl } from "./passes/palette.glsl";
import { pixelateStep } from "./passes/pixelate";
import { fieldPreset } from "./presets";
import { fieldGlsl } from "./sources/field.glsl";

/**
 * GLSL compiled ahead of time (docs/shaders/design.md, S2c notes): a live mount whose chain has a
 * fixed shape ships the text of its one program and the names of its uniforms, not the GLSL
 * generators and the stage compiler. `bun scripts/shaders/bake.ts` writes `field.baked.ts` from
 * here; a test fails when that file is stale. `mountPreset` (any chain) still compiles at run time.
 */

/** One program of a chain, with the uniforms its chunks bind, by kind of setter. */
export interface BakedProgram {
  fragment: string;
  /** Uniform name → the setter its chunk calls (`f1`, `f4v`…), in the order they are bound. */
  uniforms: Record<string, keyof UniformSetter>;
}

/** The one stage of a chain as text; throws when the chain needs several stages. */
export function bakeProgram(chain: GlChain): BakedProgram {
  const stages = compileStages(chain);
  const stage = stages[0];
  if (!stage || stages.length !== 1) throw new Error("bake: a chain of one stage only");
  const uniforms: Record<string, keyof UniformSetter> = {};
  const record =
    (kind: keyof UniformSetter) =>
    (name: string): void => {
      uniforms[name] = kind;
    };
  const set: UniformSetter = {
    f1: record("f1"),
    f2: record("f2"),
    f4v: record("f4v"),
    i1: record("i1"),
    texture: record("texture"),
  };
  const ctx = { time: 0, mouse: [0.5, 0.2] as const, res: [1, 1] as const, px: 1 };
  for (const chunk of stage.chunks)
    chunk.bind?.(set, { ...ctx, resolve: () => [0, 0, 0] as const });
  return { fragment: stage.fragment, uniforms };
}

/** The field mount's program: `fieldPreset` with the ember (`accent`) and without (`ink`). */
export interface BakedField {
  accent: string;
  ink: string;
  /** The uniform of the mode (`f1`) and of the three tones (`f4v`). */
  mode: string;
  tones: string;
}

export function bakeField(): BakedField {
  const program = (accent: boolean) =>
    bakeProgram(
      bindChain(
        fieldPreset({ mode: "ember", accent }),
        { field: fieldGlsl },
        { pixelate: pixelateStep, ordered: orderedGlsl, grid: gridGlsl, palette: paletteGlsl },
      ),
    );
  const accent = program(true);
  const ink = program(false);
  const names = (kind: keyof UniformSetter) =>
    Object.keys(accent.uniforms).filter((n) => accent.uniforms[n] === kind);
  const [mode] = names("f1");
  const [tones] = names("f4v");
  if (!mode || !tones || Object.keys(accent.uniforms).length !== 2)
    throw new Error("bake: the field binds its mode and its tones only");
  if (JSON.stringify(ink.uniforms) !== JSON.stringify(accent.uniforms))
    throw new Error("bake: both field programs bind the same uniforms");
  return { accent: accent.fragment, ink: ink.fragment, mode, tones };
}

/** The module `field.baked.ts` as written by the script. */
export function bakedFieldModule(): string {
  const f = bakeField();
  return `// Generated by \`bun scripts/shaders/bake.ts\` from \`bakeField()\` (./bake.ts): the field's GLSL,
// compiled ahead of time so that the field mount does not bundle the generators. Do not edit; a
// test fails when it is stale.

/** The fragment shader of \`fieldPreset\` with the ember, then without (\`accent: false\`). */
export const FIELD_FRAGMENT = ${JSON.stringify(f.accent)};
export const FIELD_FRAGMENT_INK = ${JSON.stringify(f.ink)};
/** Its uniforms besides the inputs: the mode (float) and the three tones (vec4[3]). */
export const FIELD_MODE_UNIFORM = ${JSON.stringify(f.mode)};
export const FIELD_TONES_UNIFORM = ${JSON.stringify(f.tones)};
`;
}
