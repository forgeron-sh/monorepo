const GENERAL: IconCategory = {
  id: "general",
  label: "General",
  description: "Names that no rule of the taxonomy recognises yet.",
};

export const CATEGORIES: readonly IconCategory[] = [
  ...RULES.map(({ id, label, description }) => ({ id, label, description })),
  GENERAL,
];

const byWord = new Map<string, string>();
for (const rule of RULES) {
  for (const word of rule.words) if (!byWord.has(word)) byWord.set(word, rule.id);
}

/** The words of a name, without variant numbers: `arrow-down-01` → `arrow`, `down`. */
export function wordsOf(name: string): string[] {
  return name.split("-").filter((w) => w !== "" && !/^\d+$/.test(w));
}

/** The variant number at the end of a name, if any: `arrow-down-01` → `01`. */
export function variantOf(name: string): string | undefined {
  return /-(\d+)$/.exec(name)?.[1];
}

/**
 * The category of a name: a known pair of words first, then the first word that is not a
 * qualifier, then any word at all, else `general`.
 */
export function categoryOf(name: string): string {
  const words = wordsOf(name);
  const set = new Set(words);
  for (const [pair, id] of COMPOUNDS) if (pair.every((w) => set.has(w))) return id;
  for (const word of words) {
    if (QUALIFIERS.has(word)) continue;
    const id = byWord.get(word);
    if (id) return id;
  }
  for (const word of words) {
    const id = byWord.get(word);
    if (id) return id;
  }
  return GENERAL.id;
}
