/**
 * The Rust sources generated from TypeScript: the binary layouts (`layout.ts` →
 * `crates/fg-blueprint/src/layout.rs`) and the bitmap face (`core/font.ts` →
 * `crates/fg-blueprint/src/font.rs`). `scripts/blueprint/gen-layout.ts` and `gen-font.ts` write
 * them; `codegen.test.ts` fails when a checked-in file is stale.
 */
import { GLYPHS } from "../core/font";
import { BLOCK_FLAGS, CODES, RECORDS, SCENE_MAGIC, BLOCKS_MAGIC, SCENE_VERSION } from "./layout";

const HEADER = (from: string, script: string) =>
  `// @generated by ${script} from ${from}: do not edit.\n// Regenerate with \`bun ${script}\`.\n`;

const snake = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();

export function layoutRust(): string {
  const out: string[] = [
    HEADER("packages/blueprint/src/engine/layout.ts", "scripts/blueprint/gen-layout.ts"),
    "//! Word offsets of the SceneBin and packed block records, and the codes of their enumerated words.\n",
    `pub const SCENE_MAGIC: u32 = 0x${SCENE_MAGIC.toString(16)};`,
    `pub const BLOCKS_MAGIC: u32 = 0x${BLOCKS_MAGIC.toString(16)};`,
    `pub const SCENE_VERSION: u32 = ${SCENE_VERSION};`,
    "",
  ];
  for (const [record, fields] of Object.entries(RECORDS)) {
    out.push(`pub mod ${snake(record).toLowerCase()} {`);
    fields.forEach((field, i) => out.push(`    pub const ${snake(field)}: usize = ${i};`));
    out.push(
      `    /// Words per record.`,
      `    pub const WORDS: usize = ${fields.length};`,
      "}",
      "",
    );
  }
  out.push("pub mod code {");
  for (const [group, codes] of Object.entries(CODES)) {
    out.push(`    pub mod ${snake(group).toLowerCase()} {`);
    for (const [name, value] of Object.entries(codes))
      out.push(`        pub const ${snake(name)}: i32 = ${value};`);
    out.push("    }");
  }
  out.push("}", "", "pub mod flags {");
  for (const [name, bit] of Object.entries(BLOCK_FLAGS))
    out.push(`    pub const ${snake(name)}: u32 = ${bit};`);
  out.push("}", "");
  return out.join("\n");
}

const rustString = (s: string) => JSON.stringify(s);
const rustChar = (c: string) =>
  c === "'" ? "'\\''" : c === "\\" ? "'\\\\'" : `'\\u{${c.codePointAt(0)!.toString(16)}}'`;

export function fontRust(): string {
  const entries = Object.entries(GLYPHS).sort(([a], [b]) => a.codePointAt(0)! - b.codePointAt(0)!);
  const out: string[] = [
    HEADER("packages/blueprint/src/core/font.ts", "scripts/blueprint/gen-font.ts"),
    "//! The bitmap face of labels (`GLYPHS` of `core/font.ts`), sorted by code point.\n",
    "/// A glyph: its first row (0 = cap height) and its rows, `#` for a pixel.",
    "pub struct Glyph {",
    "    pub top: i32,",
    "    pub rows: &'static [&'static str],",
    "}",
    "",
    "pub static GLYPHS: &[(char, Glyph)] = &[",
  ];
  for (const [ch, g] of entries)
    out.push(
      `    (${rustChar(ch)}, Glyph { top: ${g.top}, rows: &[${g.rows.map(rustString).join(", ")}] }),`,
    );
  out.push("];", "");
  return out.join("\n");
}
