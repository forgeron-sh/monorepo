import type { ColumnType } from "kysely";

// The column builders of `t` (docs/sdk.md §8). A column carries its SQL definition as data and its
// TypeScript types as phantom parameters: what a SELECT returns, whether it can be NULL, whether
// it has a default, and what a write accepts.

type ColumnKind =
  | "id"
  | "text"
  | "integer"
  | "real"
  | "boolean"
  | "date"
  | "timestamp"
  | "enum"
  | "json"
  | "ref";

export type OnDelete = "cascade" | "set null" | "restrict";

type DefaultValue = { kind: "value"; value: string | number | boolean } | { kind: "now" };

export interface ColumnDef {
  kind: ColumnKind;
  notNull: boolean;
  unique: boolean;
  default?: DefaultValue;
  onUpdateNow: boolean;
  /** `enum`: the allowed values. */
  values?: readonly string[];
  /** `ref`: the table pointed at, and what happens to this row when the target row goes. */
  references?: string;
  onDelete?: OnDelete;
}

/**
 * @typeParam S what a SELECT returns
 * @typeParam N whether the column can be NULL
 * @typeParam D whether the column has a default (so an INSERT may leave it out)
 * @typeParam W what an INSERT or UPDATE accepts
 */
export class Column<S, N extends boolean = true, D extends boolean = false, W = S> {
  // Only for the types: nothing of these exists at runtime.
  declare readonly _select: S;
  declare readonly _nullable: N;
  declare readonly _default: D;
  declare readonly _write: W;

  readonly def: ColumnDef;

  constructor(def: ColumnDef) {
    this.def = def;
  }

  private with(change: Partial<ColumnDef>): ColumnDef {
    return { ...this.def, ...change };
  }

  notNull(): Column<S, false, D, W> {
    return new Column(this.with({ notNull: true }));
  }

  unique(): Column<S, N, D, W> {
    return new Column(this.with({ unique: true }));
  }

  /** A value for rows that do not give one. A column with a default is never NULL. */
  default(value: W): Column<S, false, true, W> {
    if (typeof value === "object")
      throw new TypeError("A default is a string, a number or a boolean.");
    return new Column(
      this.with({ notNull: true, default: { kind: "value", value: value as never } }),
    );
  }

  /** The time of the insert, as an ISO 8601 string in UTC. */
  defaultNow(): Column<S, false, true, W> {
    if (this.def.kind !== "timestamp" && this.def.kind !== "date") {
      throw new TypeError("defaultNow() is for timestamp and date columns.");
    }
    return new Column(this.with({ notNull: true, default: { kind: "now" } }));
  }

  /** Set to the time of the update, whenever the row is updated without giving this column. */
  onUpdateNow(): Column<S, N, D, W> {
    if (this.def.kind !== "timestamp")
      throw new TypeError("onUpdateNow() is for timestamp columns.");
    return new Column(this.with({ onUpdateNow: true }));
  }

  onDelete(action: OnDelete): Column<S, N, D, W> {
    if (this.def.kind !== "ref") throw new TypeError("onDelete() is for ref columns.");
    return new Column(this.with({ onDelete: action }));
  }
}

const base = (kind: ColumnKind, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  kind,
  notNull: false,
  unique: false,
  onUpdateNow: false,
  ...extra,
});

/** What `ref(table)` needs of a table: its name. */
interface Named {
  readonly name: string;
}

export const t = {
  /** `TEXT PRIMARY KEY`, generated by the database: 32 hex characters, ordered by creation time. */
  id: () => new Column<string, false, true>(base("id", { notNull: true })),
  text: () => new Column<string>(base("text")),
  integer: () => new Column<number>(base("integer")),
  real: () => new Column<number>(base("real")),
  /** SQLite stores 0 and 1: a SELECT returns them, an INSERT accepts them or a boolean. */
  boolean: () => new Column<0 | 1, true, false, boolean | 0 | 1>(base("boolean")),
  /** `YYYY-MM-DD`. */
  date: () => new Column<string>(base("date")),
  /** ISO 8601 in UTC. */
  timestamp: () => new Column<string>(base("timestamp")),
  enum: <const V extends readonly [string, ...string[]]>(values: V) =>
    new Column<V[number]>(base("enum", { values })),
  /** JSON text. Not (de)serialized for you yet: write `JSON.stringify(value)`, read a string. */
  json: () => new Column<string>(base("json")),
  /** The `id` of another table, by its name or by the table itself. */
  ref: (target: Named | string) =>
    new Column<string>(
      base("ref", { references: typeof target === "string" ? target : target.name }),
    ),
};

/** The Kysely column type of a builder: what each of SELECT, INSERT and UPDATE takes. */
export type ColumnOf<C> =
  C extends Column<infer S, infer N, infer D, infer W>
    ? ColumnType<
        N extends true ? S | null : S,
        D extends true ? W | undefined : N extends true ? W | null | undefined : W,
        N extends true ? W | null : W
      >
    : never;
