// Builds crates/fg-blueprint for the browser, Node and Workers into packages/blueprint/wasm/ (the
// built module is committed, D-150: the site and TypeScript-only contributors need no Rust).
//   bun scripts/blueprint/build-wasm.ts           build and write packages/blueprint/wasm/
//   bun scripts/blueprint/build-wasm.ts --check   build, and fail unless it is byte-identical
// Needs the toolchain of `rust-toolchain.toml` (rustup, with its wasm target), `wasm-bindgen` at
// the exact version of the crate's dependency and `wasm-opt` (binaryen 116+), as
// packages/canvas/bench/build-wasm.ts. Paths are remapped so that the build does not depend on
// where the repository or the cargo home live.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";

const root = new URL("../../", import.meta.url).pathname.replace(/\/$/, "");
const dest = `${root}/packages/blueprint/wasm`;
const work = `${root}/target/blueprint-wasm`;
const check = process.argv.includes("--check");
const home = process.env.HOME ?? "";
const cargoHome = process.env.CARGO_HOME ?? `${home}/.cargo`;

const channel = /channel\s*=\s*"([^"]+)"/.exec(
  readFileSync(`${root}/rust-toolchain.toml`, "utf8"),
)?.[1];
if (!channel) throw new Error("no channel in rust-toolchain.toml");
const pinned = /wasm-bindgen = \{ version = "=([^"]+)"/.exec(
  readFileSync(`${root}/crates/fg-blueprint/Cargo.toml`, "utf8"),
)?.[1];

const tool = (name: string) => {
  const local = `${cargoHome}/bin/${name}`;
  return existsSync(local) ? local : name;
};
const run = (cmd: string, args: string[], env?: Record<string, string | undefined>) =>
  execFileSync(cmd, args, {
    cwd: root,
    stdio: ["ignore", "pipe", "inherit"],
    ...(env ? { env: { ...process.env, ...env } } : {}),
  }).toString();
const which = (bin: string) => run("rustup", ["which", "--toolchain", channel, bin]).trim();
const cargo = which("cargo");
const rustc = which("rustc");

const bindgen = tool("wasm-bindgen");
const version = run(bindgen, ["--version"]).trim().split(" ")[1];
if (version !== pinned)
  throw new Error(
    `wasm-bindgen ${version} found, the crate pins ${pinned}: cargo install --locked wasm-bindgen-cli --version =${pinned}`,
  );
const wasmOpt = tool("wasm-opt");

// The same bytes on every machine: no absolute path of this checkout or of the cargo home.
const rustflags = [
  `--remap-path-prefix=${root}=/forgeron`,
  `--remap-path-prefix=${cargoHome}=/cargo`,
];
run(
  cargo,
  [
    "build",
    "-p",
    "fg-blueprint",
    "--features",
    "wasm",
    "--target",
    "wasm32-unknown-unknown",
    "--release",
    "--target-dir",
    `${work}/cargo`,
  ],
  { RUSTC: rustc, CARGO_ENCODED_RUSTFLAGS: rustflags.join("\x1f") },
);
const raw = `${work}/raw`;
rmSync(raw, { recursive: true, force: true });
mkdirSync(raw, { recursive: true });
run(bindgen, [
  `${work}/cargo/wasm32-unknown-unknown/release/fg_blueprint.wasm`,
  "--target",
  "web",
  "--out-dir",
  raw,
]);
const out = `${work}/out`;
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
run(wasmOpt, [
  "-Oz",
  "--all-features",
  `${raw}/fg_blueprint_bg.wasm`,
  "-o",
  `${out}/fg_blueprint_bg.wasm`,
]);
// The glue, marked as generated (the linter skips it) and as the repository's formatter writes
// it, so that the committed copy stays formatted.
const banner =
  "// @generated by scripts/blueprint/build-wasm.ts (wasm-bindgen): do not edit.\n/* oxlint-disable */\n";
for (const file of readdirSync(raw).filter((f) => !f.endsWith(".wasm")))
  writeFileSync(
    `${out}/${file}`,
    execFileSync(
      `${root}/node_modules/.bin/oxfmt`,
      [`--stdin-filepath=packages/blueprint/wasm/${file}`],
      { cwd: root, input: banner + readFileSync(`${raw}/${file}`, "utf8") },
    ),
  );

const files = readdirSync(out).sort();
const kb = (b: number) => `${(b / 1024).toFixed(1)} KB`;
const wasm = readFileSync(`${out}/fg_blueprint_bg.wasm`);
console.log(
  `fg_blueprint_bg.wasm: ${kb(wasm.length)}, ${kb(gzipSync(wasm, { level: 9 }).length)} gzip`,
);

if (check) {
  const committed = existsSync(dest) ? readdirSync(dest).sort() : [];
  const differ = files.filter(
    (f) =>
      !committed.includes(f) || !readFileSync(`${out}/${f}`).equals(readFileSync(`${dest}/${f}`)),
  );
  const extra = committed.filter((f) => !files.includes(f));
  if (differ.length || extra.length) {
    console.error(
      `packages/blueprint/wasm/ is not what the crates build (${[...differ, ...extra].join(", ")}): run bun scripts/blueprint/build-wasm.ts`,
    );
    process.exit(1);
  }
  console.log("packages/blueprint/wasm/ is byte-identical to a fresh build.");
} else {
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
  for (const f of files) writeFileSync(`${dest}/${f}`, readFileSync(`${out}/${f}`));
  console.log(`wrote ${files.map((f) => `packages/blueprint/wasm/${f}`).join(", ")}`);
}
